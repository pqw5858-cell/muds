const SIZE_WORDS = [
  [/지름 (\d+)cm/g, 'Ø $1 cm'],
  [/높이 (\d+)cm/g, 'H $1 cm'],
  [/(\d+) × (\d+) × (\d+)cm/g, '$1 × $2 × $3 cm'],
  [/(\d+) × (\d+)cm/g, '$1 × $2 cm'],
  [/(\d+)ml/g, '$1 ml'],
  [/(\d+)p\b/gi, '$1 pcs'],
  [/^각 (.+?)(,|$)/, '$1 each$2'],
  [/찻잔/g, 'teacup'],
  [/술잔/g, 'liquor cup'],
  [/주병/g, 'bottle'],
  [/다관/g, 'teapot'],
  [/밥그릇/g, 'rice bowl'],
  [/국그릇/g, 'soup bowl'],
  [/접시/g, 'plate'],
  [/잔 2 pcs/g, '2 cups'],
  [/잔/g, 'cup'],
  [/ 외$/, ' and more'],
]
export const translateSize = (size) => {
  const text = SIZE_WORDS.reduce((s, [from, to]) => s.replace(from, to), size)
  return text.charAt(0).toUpperCase() + text.slice(1)
}

